import pandas as pd

# 1. Load the dataset
df = pd.read_csv("credit_applicants.csv")

# Compute exact default rate (assuming column name is 'default')
default_rate = df["default"].mean() * 100

# Compute exact percentage of missing credit_bureau_score values
missing_bureau_pct = df["credit_bureau_score"].isna().mean() * 100

print(f"Measured Default Rate: {default_rate:.2f}%")
print(f"Missing Credit Bureau Score Percentage: {missing_bureau_pct:.2f}%")

# Engineer binary is_thin_file flag (1 where missing, 0 otherwise)
df["is_thin_file"] = df["credit_bureau_score"].isna().astype(int)

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

df["is_thin_file"] = df["credit_bureau_score"].isna().astype(int)

# Separate features and target (exclude non-predictive IDs)
X = df.drop(columns=["default", "applicant_id"])
y = df["default"]

# 2. Stratified Train/Test Split (75/25, random_state=42)
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.25, stratify=y, random_state=42
)

# 3. Median Imputation (Training data only)
train_bureau_median = X_train["credit_bureau_score"].median()
X_train["credit_bureau_score"] = X_train["credit_bureau_score"].fillna(
    train_bureau_median
)
X_test["credit_bureau_score"] = X_test["credit_bureau_score"].fillna(
    train_bureau_median
)

# 4. Encode Categorical Features (One-Hot Encoding)
X_train = pd.get_dummies(X_train, columns=["employment_type"], drop_first=True)
X_test = pd.get_dummies(X_test, columns=["employment_type"], drop_first=True)
X_train, X_test = X_train.align(X_test, join="left", axis=1, fill_value=0)

# 5. Feature Scaling (Fit on Train only, Transform both)
scaler = StandardScaler()
X_train_scaled = pd.DataFrame(
    scaler.fit_transform(X_train), columns=X_train.columns, index=X_train.index
)
X_test_scaled = pd.DataFrame(
    scaler.transform(X_test), columns=X_test.columns, index=X_test.index
)

from sklearn.linear_model import LogisticRegression
from sklearn.metrics import classification_report, roc_auc_score
from sklearn.tree import DecisionTreeClassifier

# 1. Initialize and train Logistic Regression
lr_model = LogisticRegression(random_state=42)
lr_model.fit(X_train_scaled, y_train)

# Predict class labels and probabilities
lr_preds = lr_model.predict(X_test_scaled)
lr_probs = lr_model.predict_proba(X_test_scaled)[:, 1]

# 2. Initialize and train Decision Tree Classifier
dt_model = DecisionTreeClassifier(random_state=42)
dt_model.fit(X_train_scaled, y_train)

# Predict class labels and probabilities
dt_preds = dt_model.predict(X_test_scaled)
dt_probs = dt_model.predict_proba(X_test_scaled)[:, 1]

# Evaluate models
print("Logistic Regression ROC-AUC:", roc_auc_score(y_test, lr_probs))
print("Decision Tree ROC-AUC:", roc_auc_score(y_test, dt_probs))

