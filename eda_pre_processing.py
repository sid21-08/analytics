import pandas as pd
from sklearn.ensemble import IsolationForest
from sklearn.preprocessing import StandardScaler

# 1. Load the dataset
df = pd.read_csv("txn_behaviour.csv")

# 2. Select numeric behavioural features
features = ["txn_hour", "is_new_device", "txn_amount_inr"]
X = df[features]

# 3. Standardize numeric features
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# 4. Fit Isolation Forest with exact contamination rate (15 / 265)
contamination_rate = 15 / 265  # ~0.0566 (5.66%)
iso_forest = IsolationForest(contamination=contamination_rate, random_state=42)

# Predict (-1 indicates anomaly, 1 indicates normal)
df["anomaly_pred"] = iso_forest.fit_predict(X_scaled)
df["is_flagged"] = df["anomaly_pred"] == -1

# 5. Recall Check against Ground Truth (txn_id starting with 'BTXNA')
df["is_ground_truth_anomaly"] = df["txn_id"].astype(str).str.startswith("BTXNA")

total_seeded_anomalies = df["is_ground_truth_anomaly"].sum()
flagged_seeded_anomalies = (
    df["is_ground_truth_anomaly"] & df["is_flagged"]
).sum()
recall = (flagged_seeded_anomalies / total_seeded_anomalies) * 100

print(
    f"Seeded Anomalies Flagged: {flagged_seeded_anomalies} out of {total_seeded_anomalies}"
)
print(f"Anomaly Detection Recall: {recall:.2f}%")