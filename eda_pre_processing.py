# Bucket into 4 probability quartiles
pricing_df["risk_tier"] = pd.qcut(
    pricing_df["predicted_prob"],
    q=4,
    labels=["Tier 1 (Low)", "Tier 2 (Med-Low)", "Tier 3 (Med-High)", "Tier 4 (High)"],
)

# Define illustrative interest rate ranges
apr_map = {
    "Tier 1 (Low)": "9.5% - 12.0%",
    "Tier 2 (Med-Low)": "12.5% - 15.5%",
    "Tier 3 (Med-High)": "16.0% - 20.0%",
    "Tier 4 (High)": "21.0% - 28.0%",
}

# Aggregate metrics per tier
tier_summary = (
    pricing_df.groupby("risk_tier", observed=False)
    .agg(
        applicant_count=("actual_default", "count"),
        min_prob=("predicted_prob", "min"),
        max_prob=("predicted_prob", "max"),
        observed_defaults=("actual_default", "sum"),
        observed_default_rate=("actual_default", "mean"),
    )
    .reset_index()
)

