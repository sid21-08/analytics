# Macroeconomic / Market Parameters
R_F = 0.04  # Risk-free rate (4%)
E_RM = 0.10  # Expected market return (10%)
PAIRWISE_RHO = 0.3  # Pairwise correlation coefficient (rho = 0.3)


# -----------------------------------------------------------------------------
# STAGE 2: ACT (Tool Function)
# -----------------------------------------------------------------------------
def get_stock_data(ticker: str) -> dict:
    """Look up beta, analyst_expected_return, and std_dev from STOCK_UNIVERSE."""
    if ticker not in STOCK_UNIVERSE:
        raise ValueError(f"Ticker '{ticker}' not found in STOCK_UNIVERSE.")
    return STOCK_UNIVERSE[ticker]


# -----------------------------------------------------------------------------
# AGENT LOOP IMPLEMENTATION
# -----------------------------------------------------------------------------
def run_advisory_agent(investor_profile: dict) -> dict:
    investor_id = investor_profile.get("id", "UNKNOWN")
    risk_tolerance = (
        investor_profile.get("risk_tolerance", "").strip().capitalize()
    )

    # =========================================================================
    # STAGE 1: THINK (Required Prescribed Allocation Table)
    # =========================================================================
    if risk_tolerance == "Conservative":
        tickers = ["PAYBOND", "PAYGOLD", "PAYRETAIL"]
    elif risk_tolerance == "Moderate":
        tickers = ["PAYRETAIL", "PAYINFRA", "PAYGOLD"]
    elif risk_tolerance == "Aggressive":
        tickers = ["PAYTECH", "PAYFIN", "PAYINFRA"]
    else:
        raise ValueError(
            f"Invalid or unsupported risk tolerance: '{risk_tolerance}'"
        )

    # Prescribed equal weights (1/3 each)
    weights = [1.0 / 3.0, 1.0 / 3.0, 1.0 / 3.0]

    # =========================================================================
    # STAGE 2: ACT (Tool Call Execution)
    # =========================================================================
    stock_data_list = [get_stock_data(t) for t in tickers]

    # =========================================================================
    # STAGE 3: OBSERVE -> DECIDE (CAPM Return & Portfolio Variance Math)
    # =========================================================================
    # 1. CAPM-Expected Return per stock using ONLY beta: E(R) = R_f + beta * (E(R_m) - R_f)
    capm_returns = [
        R_F + data["beta"] * (E_RM - R_F) for data in stock_data_list
    ]

    # Portfolio Expected Return (weight-averaged across the 3 tickers)
    portfolio_expected_return = sum(
        w * r for w, r in zip(weights, capm_returns)
    )

    # 2. Portfolio Variance Formula:
    #    Var(R_p) = sum_i (w_i^2 * sigma_i^2) + 2 * sum_{i<j} (w_i * w_j * Cov(R_i, R_j))
    #    with Cov(R_i, R_j) = rho * sigma_i * sigma_j
    sigmas = [data["std_dev"] for data in stock_data_list]

    # Direct Variance Component: sum(w_i^2 * sigma_i^2)
    var_direct = sum((w**2) * (s**2) for w, s in zip(weights, sigmas))

    # Covariance Component: 2 * sum_{i<j} (w_i * w_j * rho * sigma_i * sigma_j)
    cov_terms = 0.0
    for i in range(len(sigmas)):
        for j in range(i + 1, len(sigmas)):
            cov_terms += (
                2
                * weights[i]
                * weights[j]
                * (PAIRWISE_RHO * sigmas[i] * sigmas[j])
            )

    portfolio_variance = var_direct + cov_terms

    # Convert variance to portfolio standard deviation
    portfolio_std_dev = math.sqrt(portfolio_variance)

    # =========================================================================
    # HUMAN-IN-THE-LOOP ESCALATION CHECK
    # =========================================================================
    # If computed portfolio standard deviation exceeds 20% (0.20), escalate to human advisor
    if portfolio_std_dev > 0.20:
        status = "ESCALATED_TO_HUMAN_ADVISOR"
    else:
        status = "FINALIZED"

    # Return output dictionary with all computed numbers attached
    return {
        "investor_id": investor_id,
        "risk_tolerance": risk_tolerance,
        "prescribed_allocation": dict(zip(tickers, weights)),
        "portfolio_capm_expected_return": portfolio_expected_return,
        "portfolio_std_dev": portfolio_std_dev,
        "portfolio_std_dev_pct": f"{portfolio_std_dev * 100:.2f}%",
        "status": status,
    }


