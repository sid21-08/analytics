import math
import os
import import_ipynb
from stock_universe import STOCK_UNIVERSE

# Environment Control Flag
MOCK_LLM = int(os.getenv("MOCK_LLM", 1))

# Macroeconomic & Market Parameters
R_F = 0.04  # Risk-free rate (4%)
E_RM = 0.10  # Expected market return (10%)
PAIRWISE_RHO = 0.3  # Correlation coefficient (rho = 0.3)


# Tool Call Simulation
def get_stock_data(ticker: str) -> dict:
    if ticker not in STOCK_UNIVERSE:
        raise ValueError(f"Ticker '{ticker}' not found in STOCK_UNIVERSE.")
    return STOCK_UNIVERSE[ticker]


# Agent Loop Execution
def run_advisory_agent(investor_profile: dict, mock_llm: int = MOCK_LLM) -> dict:
    investor_id = investor_profile.get("id", "UNKNOWN")
    risk_tolerance = (
        investor_profile.get("risk_tolerance", "").strip().capitalize()
    )

    # STAGE 1: THINK (Allocation Mapping)
    if risk_tolerance == "Conservative":
        tickers = ["PAYBOND", "PAYGOLD", "PAYRETAIL"]
    elif risk_tolerance == "Moderate":
        tickers = ["PAYRETAIL", "PAYINFRA", "PAYGOLD"]
    elif risk_tolerance == "Aggressive":
        tickers = ["PAYTECH", "PAYFIN", "PAYINFRA"]
    else:
        raise ValueError(f"Unsupported risk tolerance: {risk_tolerance}")

    weights = [1.0 / 3.0] * 3  # Equal weight across 3 tickers

    # STAGE 2: ACT (Tool Calls)
    stock_data_list = [get_stock_data(t) for t in tickers]

    # STAGE 3: OBSERVE -> DECIDE (CAPM & Risk Calculations)
    # 1. CAPM-Expected Return per stock using ONLY beta
    capm_returns = [
        R_F + data["beta"] * (E_RM - R_F) for data in stock_data_list
    ]
    portfolio_return = sum(w * r for w, r in zip(weights, capm_returns))

    # 2. Portfolio Variance & Standard Deviation with rho = 0.3
    sigmas = [data["std_dev"] for data in stock_data_list]
    var_direct = sum((w**2) * (s**2) for w, s in zip(weights, sigmas))
    cov_terms = sum(
        2 * weights[i] * weights[j] * (PAIRWISE_RHO * sigmas[i] * sigmas[j])
        for i in range(len(sigmas))
        for j in range(i + 1, len(sigmas))
    )
    portfolio_variance = var_direct + cov_terms
    portfolio_std_dev = math.sqrt(portfolio_variance)

    # Human-in-the-loop Escalation Check
    status = (
        "ESCALATED_TO_HUMAN_ADVISOR" if portfolio_std_dev > 0.20 else "FINALIZED"
    )

    # Narrative Sentence Generation (Gated by MOCK_LLM)
    tickers_str = ", ".join(tickers)
    if mock_llm == 1:
        narrative = (
            f"For {risk_tolerance} investor {investor_id}, we recommend an allocation across "
            f"{tickers_str} with an expected portfolio return of {portfolio_return:.1%} "
            f"and volatility of {portfolio_std_dev:.1%}."
        )
    else:
        # Extension mode for LLM generation
        narrative = f"Natural language summary for investor {investor_id} across {tickers_str}."

    return {
        "investor_id": investor_id,
        "risk_tolerance": risk_tolerance,
        "tickers": tickers_str,
        "expected_return": portfolio_return,
        "volatility": portfolio_std_dev,
        "status": status,
        "narrative": narrative,
    }


